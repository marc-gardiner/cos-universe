with open('C:/Users/marca/projects/cos-universe/viz/butterfly-effect-v2.html', encoding='utf-8') as f:
    content = f.read()

scenarios = re.findall(r"id:\s*'([\w\-]+)',\s*phase:\s*(\d+)", content)
print(f"Found {len(scenarios)} top-level scenarios")

for sid, phase in scenarios:
    pattern = r"(id:\s*'" + re.escape(sid) + r"',\s*phase:\s*" + phase + r",)"
    scenes  = json.dumps(SCENE_REFS.get(sid, []))
    loc     = "'" + LOCATION_REFS.get(sid, '') + "'"
    prereqs = json.dumps(PREREQS.get(sid, []))
    replacement = r"\1\n    sceneRef: " + scenes + r",\n    locationRef: " + loc + r",\n    prereqs: " + prereqs + r","
    new_content, count = re.subn(pattern, replacement, content)
    if count == 0:
        print(f"  WARNING no match: {sid} phase={phase}")
    elif count > 1:
        print(f"  WARNING multi-match: {sid} phase={phase} ({count})")
    content = new_content

injected = content.count('sceneRef:')
print(f"sceneRef fields inserted: {injected}")

with open('C:/Users/marca/projects/cos-universe/viz/butterfly-effect-v2.html', 'w', encoding='utf-8') as f:
    f.write(content)

